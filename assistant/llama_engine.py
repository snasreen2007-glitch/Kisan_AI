    def chat(
        self,
        query: str,
        lang: str = "en",
        scan_context: Optional[Dict[str, Any]] = None
    ) -> Dict[str, Any]:
        """
        Multimodal and Multilingual conversational response powered by Llama 3.2.
        """
        # 1. Statutory CIB&RC Safety Gate
        is_safe, refusal = self.safety.validate_query(query, lang)
        if not is_safe:
            return {
                "answer": refusal,
                "safety_triggered": True,
                "model": "Llama-3.2-1B-Instruct",
                "lang": lang,
                "multimodal": False
            }

        # 2. Integrate visual context if provided
        visual_prefix = ""
        is_multimodal = False
        if scan_context:
            is_multimodal = True
            c_crop = scan_context.get("crop", "crop")
            c_prob = scan_context.get("problem", "condition")
            c_sev = scan_context.get("severity_percent", 0)
            c_stage = scan_context.get("stage", "")

            if lang == "te":
                visual_prefix = f"[ఫోటో పరిశీలన: {c_crop} లో {c_prob}, తీవ్రత {c_sev}% ({c_stage})]: "
            elif lang == "hi":
                visual_prefix = f"[तस्वीर विश्लेषण: {c_crop} में {c_prob}, गंभीरता {c_sev}% ({c_stage})]: "
            else:
                visual_prefix = f"[Photo Inspection: {c_crop} with {c_prob}, severity {c_sev}% ({c_stage})]: "

        # 3. Query RAG engine
        rag_res = self.rag.process_query(query, lang=lang)
        answer = rag_res["answer"]

        # 4. Check if Docker Model Runner is active (docker model run hf.co/meta-llama/Llama-3.2-1B-Instruct)
        if self.docker_bridge.is_docker_model_running():
            docker_out = self.docker_bridge.generate(
                prompt=f"Verified Agricultural Knowledge:\n{rag_res.get('context', '')}\n\nFarmer Question in {lang}: {query}",
                system_prompt="You are the Meta Llama 3.2 1B Instruct Crop Assistant. Answer concisely without recommending unverified chemical dosages."
            )
            if docker_out:
                answer = docker_out

        if visual_prefix:
            answer = f"{visual_prefix}{answer}"

        return {
            "answer": answer,
            "safety_triggered": False,
            "model": "Llama-3.2-1B-Instruct",
            "lang": lang,
            "multimodal": is_multimodal,
            "records": rag_res.get("records", [])
        }


